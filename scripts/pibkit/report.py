"""Generate Markdown reports from the inventory and the latest recorded results.

Only facts recorded by actual runs (reports/generated/results-latest.json and
JUnit XML files) are reported. Checks never executed appear as NOT RUN.
"""

from __future__ import annotations

import datetime as dt
import json
import xml.etree.ElementTree as ET
from collections import Counter

from .core import REPO_ROOT
from .inventory import load_inventory
from .runner import RESULTS_DIR, load_matrix

REPORTS = REPO_ROOT / "reports"
HEADER = "<!-- Generated by `python scripts/pib.py report`. Do not edit by hand. -->\n\n"


def _latest() -> dict:
    path = RESULTS_DIR / "results-latest.json"
    return json.loads(path.read_text(encoding="utf-8"))["results"] if path.exists() else {}


def _status(results: dict, check_id: str) -> str:
    return results.get(check_id, {}).get("status", "NOT RUN")


def _technology_inventory(inv: dict) -> str:
    rows = ["| Technology | Category | Path | Status | Classification | Version policy | Tested version |", "|---|---|---|---|---|---|---|"]
    for t in sorted(inv["technologies"], key=lambda x: (x["category"], x["name"].lower())):
        path = f"[`{t['path']}`](../{t['path']})" if t["status"] != "planned" else f"`{t['path']}`"
        rows.append(
            f"| {t['name']} | {t['category']} | {path} | {t['status']} | {t.get('classification', '-')} | "
            f"{t.get('version_policy', '-')} | {t.get('tested_version') or 'not tested'} |"
        )
    counts = Counter(t["status"] for t in inv["technologies"])
    summary = ", ".join(f"**{k}**: {v}" for k, v in sorted(counts.items()))
    return (
        "# Technology Inventory\n\n" + HEADER + "Source of truth: [`inventory/technologies.yaml`](../inventory/technologies.yaml).\n\n"
        "Status meanings: `implemented` = configs + validation in this repo; `reference` = documented "
        "reference with example configuration but limited/no automated validation; `planned` = on the roadmap, "
        "no content yet.\n\n"
        f"Totals: {summary} (of {len(inv['technologies'])}).\n\n" + "\n".join(rows) + "\n"
    )


def _coverage(inv: dict, results: dict) -> str:
    rows = ["| Technology | Status | Documented | Validators (latest result) |", "|---|---|---|---|"]
    validated = Counter()
    for t in sorted(inv["technologies"], key=lambda x: (x["category"], x["id"])):
        if t["status"] == "planned":
            continue
        documented = "yes" if (REPO_ROOT / t["path"] / "README.md").exists() or (REPO_ROOT / t["path"]).is_file() else "no"
        vals = t.get("validators", [])
        states = [f"{v}: {_status(results, v)}" for v in vals]
        for v in vals:
            validated[_status(results, v)] += 1
        rows.append(f"| {t['name']} | {t['status']} | {documented} | {'<br>'.join(states) or 'none (documentation only)'} |")
    return (
        "# Configuration Coverage\n\n"
        + HEADER
        + "Maps each implemented/reference technology to the validators that cover it and the result of the "
        "most recent recorded run on this machine or in CI. `NOT RUN` means the validator was never executed "
        "in the recorded environment (usually because a tool such as Docker was unavailable).\n\n"
        f"Validator-technology links by latest status: {dict(validated)}\n\n" + "\n".join(rows) + "\n"
    )


def _validation(results: dict) -> str:
    matrix = {c["id"]: c for c in load_matrix()["checks"]}
    rows = ["| Stage | Check | Status | Targets | Duration (s) | Recorded at | Notes |", "|---|---|---|---|---|---|---|"]
    for cid, c in matrix.items():
        r = results.get(cid)
        if r:
            note = ""
            if r["status"] in ("NOT RUN", "FAIL"):
                note = (r["details"][0] if r["details"] else "").splitlines()[0][:140].replace("|", "\\|")
            rows.append(
                f"| {c['stage']} | `{cid}` | **{r['status']}** | {r['targets']} | {r['duration_s']} | {r['generated_at']} | {note} |"
            )
        else:
            rows.append(f"| {c['stage']} | `{cid}` | **NOT RUN** | - | - | never | not executed in recorded runs |")
    envs = {json.dumps(r.get("environment", {}), sort_keys=True) for r in results.values()}
    counts = Counter(results.get(cid, {}).get("status", "NOT RUN") for cid in matrix)
    return (
        "# Validation Results\n\n" + HEADER + f"Recorded environment(s): {', '.join(envs) or 'none'}\n\n"
        f"Totals across {len(matrix)} matrix checks: {dict(counts)}\n\n" + "\n".join(rows) + "\n"
    )


def _tests() -> str:
    rows = ["| Suite | Tests | Passed | Failed | Errors | Skipped | Time (s) |", "|---|---|---|---|---|---|---|"]
    skipped_rows = []
    for junit in sorted(RESULTS_DIR.glob("junit-*.xml")):
        root = ET.parse(junit).getroot()  # noqa: S314 - locally generated
        suites = [root] if root.tag == "testsuite" else list(root)
        t = Counter()
        for s in suites:
            for k in ("tests", "failures", "errors", "skipped"):
                t[k] += int(s.get(k, 0))
            t["time"] += float(s.get("time", 0))
            for case in s.iter("testcase"):
                sk = case.find("skipped")
                if sk is not None:
                    msg = (sk.get("message") or "").replace("|", "\\|")[:160]
                    skipped_rows.append(f"| {junit.stem[6:]} | `{case.get('name')}` | {msg} |")
        passed = t["tests"] - t["failures"] - t["errors"] - t["skipped"]
        rows.append(f"| {junit.stem[6:]} | {t['tests']} | {passed} | {t['failures']} | {t['errors']} | {t['skipped']} | {t['time']:.1f} |")
    body = "\n".join(rows)
    if skipped_rows:
        body += "\n\n## Skipped tests (NOT RUN) and reasons\n\n| Suite | Test | Reason |\n|---|---|---|\n" + "\n".join(skipped_rows)
    return "# Test Results\n\n" + HEADER + "Aggregated from JUnit XML written by pytest suites.\n\n" + body + "\n"


def generate() -> int:
    inv = load_inventory()
    results = _latest()
    stamp = dt.datetime.now(dt.UTC).isoformat(timespec="seconds")
    outputs = {
        "technology-inventory.md": _technology_inventory(inv),
        "configuration-coverage.md": _coverage(inv, results),
        "validation-results.md": _validation(results),
        "test-results.md": _tests(),
    }
    for name, text in outputs.items():
        (REPORTS / name).write_text(text.replace(HEADER, HEADER + f"_Generated: {stamp}_\n\n", 1), encoding="utf-8")
        print(f"wrote reports/{name}")
    return 0
